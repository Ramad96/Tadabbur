import type { MosqueRow, ReciterRow, RecitationRow, ReflectionRow } from "../../lib/database.types.ts";
import { MOSQUES, RECITATIONS, SAMPLE_AUDIO_URL } from "./london.ts";

/** Stable ids so seeding twice updates rather than duplicates. */
const id = (kind: "a" | "b" | "c" | "d", n: number) =>
  `00000000-0000-4000-8000-${kind.repeat(4)}${String(n).padStart(8, "0")}`;

/** "2026-09-14", "20:41" in Europe/London → UTC ISO string, honouring BST. */
export function londonToIso(date: string, time: string) {
  const [y, mo, d] = date.split("-").map(Number);
  const [h, mi] = time.split(":").map(Number);
  const guess = Date.UTC(y, mo - 1, d, h, mi);
  const offset = new Intl.DateTimeFormat("en-GB", { timeZone: "Europe/London", timeZoneName: "shortOffset" })
    .formatToParts(new Date(guess))
    .find((p) => p.type === "timeZoneName")!.value; // "GMT" or "GMT+1"
  const hours = Number(offset.replace("GMT", "") || 0);
  return new Date(guess - hours * 3_600_000).toISOString();
}

type Insert<T, Omitted extends keyof T> = Omit<T, Omitted>;

export function buildSeedRows() {
  const mosqueId = new Map(MOSQUES.map((m, i) => [m.key, id("a", i + 1)]));

  const mosques: Insert<MosqueRow, "lat" | "lng" | "created_at" | "created_by">[] = MOSQUES.map((m) => ({
    id: mosqueId.get(m.key)!,
    name: m.name,
    address: m.address,
    city: m.city,
    country: m.country,
    location: `SRID=4326;POINT(${m.lng} ${m.lat})`,
    website: m.website ?? null,
    timezone: "Europe/London",
    verified: true,
  }));

  const reciters: Insert<ReciterRow, "created_at" | "updated_at" | "created_by">[] = RECITATIONS.map(
    (r, i) => ({
      id: id("b", i + 1),
      profile_id: null,
      name: r.reciter.name,
      photo_url: null,
      bio: null,
      age_range: r.reciter.ageRange,
      occupation: r.reciter.occupation,
      heritage: r.reciter.heritage,
      consent_public: true,
      consent_photo: false,
      is_sample: true,
    }),
  );

  const recitations: Insert<RecitationRow, "created_at" | "updated_at" | "approved_at" | "created_by">[] =
    RECITATIONS.map((r, i) => ({
      id: id("c", i + 1),
      reciter_id: id("b", i + 1),
      mosque_id: mosqueId.get(r.mosque)!,
      surah: r.surah,
      ayah_start: r.ayahStart,
      ayah_end: r.ayahEnd,
      audio_url: SAMPLE_AUDIO_URL,
      duration_sec: r.durationSec,
      recorded_at: londonToIso(r.date, r.time),
      prayer: r.prayer,
      status: "approved",
      rejection_reason: null,
      is_sample: true,
    }));

  const reflections: Insert<ReflectionRow, "created_at">[] = RECITATIONS.flatMap((r, i) => {
    const recitation_id = id("c", i + 1);
    const base = { recitation_id, answer_text: null, favourite_surah: null, favourite_ayah: null };
    return [
      { ...base, id: id("d", i * 3 + 1), question_key: "why_surah" as const, answer_text: r.why },
      {
        ...base,
        id: id("d", i * 3 + 2),
        question_key: "favourite_ayah" as const,
        favourite_surah: r.favourite[0],
        favourite_ayah: r.favourite[1],
      },
      { ...base, id: id("d", i * 3 + 3), question_key: "where_learned" as const, answer_text: r.learned },
    ];
  });

  return { mosques, reciters, recitations, reflections };
}

export type SeedRows = ReturnType<typeof buildSeedRows>;

/** Tables in dependency order, for inserting (reverse it for deleting). */
export const SEED_TABLES = ["mosques", "reciters", "recitations", "reflections"] as const;

function literal(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replaceAll("'", "''")}'`;
}

/** Idempotent SQL: upserts every sample row by id. */
export function toSql(rows: SeedRows) {
  const out = [
    "-- London sample data. Generated by `pnpm db:seed:sql` from data/seed/london.ts. Do not edit.",
    "-- Safe to run more than once. Remove before launch with: delete from tadabbur.reciters where is_sample;",
    "begin;",
  ];
  for (const table of SEED_TABLES) {
    const list = rows[table] as Record<string, unknown>[];
    const cols = Object.keys(list[0]);
    const updates = cols.filter((c) => c !== "id").map((c) => `${c} = excluded.${c}`);
    out.push(
      `insert into tadabbur.${table} (${cols.join(", ")}) values`,
      list.map((r) => `  (${cols.map((c) => literal(r[c])).join(", ")})`).join(",\n"),
      `on conflict (id) do update set ${updates.join(", ")};`,
    );
  }
  out.push("commit;", "");
  return out.join("\n");
}
